#!/usr/bin/env python3
"""Generates the fork's launcher icon overlay (FORK:tasks-org).

Every launcher icon of the app (default, round, supporter and the 31 date icons) gets a "task done"
badge in its bottom-right corner, so KashCal Tasks is told apart from the original KashCal on the
home screen.

The overlay replaces the artwork files themselves and keeps their names, so the adaptive-icon
wrappers in app/src/main/res/mipmap-anydpi-v26 (and the tests that read them) stay untouched:
- date icon foregrounds (vectors): the original vector with the badge appended;
- default and supporter foregrounds (PNGs): the original image with the badge drawn on it.

The themed (monochrome) layers are left alone: a themed icon is a single tint, so a badge would
merge with the art, and upstream tests pin those vectors to exactly the card, tabs and numeral.

Run from the repository root after the upstream changes any of these icons:

    python3 app/src/fork/tools/gen_icons.py
"""
import pathlib
import re

from PIL import Image, ImageDraw

FORK = pathlib.Path(__file__).resolve().parents[1]
RES = FORK / "res"
MAIN = FORK.parent / "main" / "res"

NOTE = "<!-- FORK:tasks-org Generated by app/src/fork/tools/gen_icons.py: the original icon art plus the task badge. -->\n"

# The badge is drawn in the 108dp adaptive canvas, bottom-right, inside the circular mask. The
# vector layers use an 88-unit viewport scaled to 108dp, so the group scale 88/108 puts the badge
# coordinates back in dp.
UNDO_VIEWPORT = 88 / 108

BADGE_COLOR = """    <group android:scaleX="{s}" android:scaleY="{s}">
        <path android:fillColor="#020727" android:pathData="M73,72m-9.2,0a9.2,9.2 0 1,1 18.4,0a9.2,9.2 0 1,1 -18.4,0" />
        <path android:fillColor="#FFFFFF" android:pathData="M73,72m-7.6,0a7.6,7.6 0 1,1 15.2,0a7.6,7.6 0 1,1 -15.2,0" />
        <path android:fillColor="#00000000" android:strokeColor="#16A34A" android:strokeWidth="2.1" android:strokeLineCap="round" android:strokeLineJoin="round" android:pathData="M69,72.3L71.9,75.2L77.2,68.8" />
    </group>
""".format(s=f"{UNDO_VIEWPORT:.5f}")

def split_vector(text: str):
    head_end = text.index(">", text.index("<vector")) + 1
    tail = text.rindex("</vector>")
    return text[:head_end] + "\n", text[head_end:tail], text[tail:]


def badge_vector(src: pathlib.Path, dst: pathlib.Path) -> None:
    head, body, tail = split_vector(src.read_text())
    out = head + NOTE + body + BADGE_COLOR + tail
    dst.parent.mkdir(parents=True, exist_ok=True)
    dst.write_text(out)


def badge_png(src: pathlib.Path, dst: pathlib.Path) -> None:
    """Draws the badge on the 108dp-based foreground PNG (any density), 4x supersampled."""
    base = Image.open(src).convert("RGBA")
    size = base.width
    k = size / 108.0
    ss = 4
    layer = Image.new("RGBA", (size * ss, size * ss), (0, 0, 0, 0))
    d = ImageDraw.Draw(layer)

    def disc(r: float, fill) -> None:
        cx, cy = 73 * k * ss, 72 * k * ss
        d.ellipse([cx - r * k * ss, cy - r * k * ss, cx + r * k * ss, cy + r * k * ss], fill=fill)

    disc(9.2, (0x02, 0x07, 0x27, 255))
    disc(7.6, (255, 255, 255, 255))
    pts = [(69, 72.3), (71.9, 75.2), (77.2, 68.8)]
    px = [(x * k * ss, y * k * ss) for x, y in pts]
    w = 2.1 * k * ss
    green = (0x16, 0xA3, 0x4A, 255)
    d.line(px, fill=green, width=round(w), joint="curve")
    for x, y in (px[0], px[2]):  # round caps
        d.ellipse([x - w / 2, y - w / 2, x + w / 2, y + w / 2], fill=green)
    layer = layer.resize((size, size), Image.LANCZOS)
    dst.parent.mkdir(parents=True, exist_ok=True)
    Image.alpha_composite(base, layer).save(dst)


def main() -> None:
    drawables = MAIN / "drawable"
    out_d = RES / "drawable"
    days = sorted(int(p.stem.split("_")[3]) for p in drawables.glob("ic_launcher_day_*_foreground.xml"))
    for stale in out_d.glob("*.xml"):
        stale.unlink()
    for d in days:
        badge_vector(drawables / f"ic_launcher_day_{d}_foreground.xml", out_d / f"ic_launcher_day_{d}_foreground.xml")
    pngs = 0
    for density in sorted(MAIN.glob("mipmap-*dpi")):
        for name in ("ic_launcher_foreground.png", "ic_launcher_supporter_foreground.png"):
            if (density / name).exists():
                badge_png(density / name, RES / density.name / name)
                pngs += 1
    print(f"wrote {len(days)} day icon foregrounds and {pngs} PNG foregrounds")


if __name__ == "__main__":
    main()
